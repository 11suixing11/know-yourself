#!/usr/bin/env node
/**
 * gen-design-tokens.mjs — regenerate the YAML front-matter of DESIGN.md from
 * the live stylesheets.
 *
 * Single source of truth: `tokens.css` keeps the structural scale,
 * `src/app/refactor.css` owns the active morning-light palette in its :root
 * and .dark blocks. This script reproduces the production cascade (tokens
 * first, refactor second — later declarations win), resolves whole-value
 * `var()` references to their underlying values, and writes the merged
 * tokens into the DESIGN.md front-matter. Only the front-matter block is
 * touched; the prose below it is never modified.
 *
 * Usage: node scripts/gen-design-tokens.mjs   (or: npm run design:tokens)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, "");

function block(css, selector) {
  const m = css.match(new RegExp(escapeRe(selector) + String.raw`\s*\{([\s\S]*?)\}`));
  return m ? m[1] : "";
}

function decls(blockText) {
  const map = new Map();
  const re = /(--[\w-]+)\s*:\s*([^;]+);/g;
  let m;
  while ((m = re.exec(blockText))) map.set(m[1], m[2].trim());
  return map;
}

/** Later maps win, first-seen order preserved. */
function layer(...maps) {
  const out = new Map();
  for (const m of maps) for (const [k, v] of m) out.set(k, v);
  return out;
}

/** Resolve whole-value var() chains against a scope; keep color-mix() raw. */
function resolve(scope, key, depth = 0) {
  const value = scope.get(key);
  if (value === undefined || depth > 8) return undefined;
  const wholeVar = value.match(/^var\((--[\w-]+)\)$/);
  return wholeVar ? resolve(scope, wholeVar[1], depth + 1) : value;
}

const tokensCss = stripComments(read("tokens.css"));
const refactorCss = stripComments(read("src/app/refactor.css"));

// Production cascade: tokens.css base, refactor.css overrides; .dark layers
// on top of the merged :root scope (undefined-in-dark keys inherit light).
const lightScope = layer(
  decls(block(tokensCss, ":root")),
  decls(block(refactorCss, ":root")),
);
const darkScope = layer(
  lightScope,
  decls(block(tokensCss, ".dark")),
  decls(block(refactorCss, ".dark")),
);

const colorNames = [...lightScope.keys()].filter(
  (k) => k.startsWith("--color-") || k === "--surface-contrast" || k === "--surface-contrast-ink",
);

const group = (scope, names) =>
  Object.fromEntries(
    names
      .filter((n) => resolve(scope, n) !== undefined)
      .map((n) => [n.replace(/^--/, ""), resolve(scope, n)]),
  );

const spaceNames = ["--space-3xs", "--space-2xs", "--space-xs", "--space-sm", "--space-md", "--space-lg", "--space-xl", "--space-2xl", "--space-3xl"];
const textNames = ["--text-2xs", "--text-xs", "--text-sm", "--text-md", "--text-lg", "--text-xl", "--text-2xl", "--text-3xl", "--text-display"];
const trackingNames = ["--tracking-display", "--tracking-title", "--tracking-body", "--tracking-label"];
const radiusNames = ["--radius-control", "--radius-panel", "--radius-media", "--radius-pill"];
const motionNames = ["--duration-short", "--duration-medium", "--ease-out"];
const layoutNames = ["--layout-max", "--header-height", "--banner-height"];
const shadowNames = [...lightScope.keys()].filter((k) => k.startsWith("--shadow-"));
const meterNames = [...lightScope.keys()].filter((k) => k.startsWith("--meter-"));
const fontNames = ["--font-display", "--font-body", "--font-code"];

const q = (s) => JSON.stringify(s);
const emit = (indent, obj) =>
  Object.entries(obj).map(([k, v]) => `${indent}${k}: ${q(v)}`).join("\n");

const yaml = [
  `name: know-yourself`,
  `skin: "morning light — warm, cozy, everyday (2026-09-19)"`,
  `palette_source: "src/app/refactor.css (:root / .dark); structural scale: tokens.css"`,
  `generated: ${new Date().toLocaleDateString("sv")}`,
  `note: "Generated by scripts/gen-design-tokens.mjs (npm run design:tokens). Never hand-edit this header — regenerate it."`,
  `colors:`,
  `  light:`,
  emit("    ", group(lightScope, colorNames)),
  `  dark:`,
  emit("    ", group(darkScope, colorNames)),
  `type:`,
  emit("  ", group(lightScope, fontNames)),
  `  scale:`,
  emit("    ", group(lightScope, textNames)),
  `  tracking:`,
  emit("    ", group(lightScope, trackingNames)),
  `space:`,
  emit("  ", group(lightScope, spaceNames)),
  `radius:`,
  emit("  ", group(lightScope, radiusNames)),
  `motion:`,
  emit("  ", group(lightScope, motionNames)),
  `layout:`,
  emit("  ", group(lightScope, layoutNames)),
  `meter:`,
  emit("  ", group(lightScope, meterNames)),
  `shadows:`,
  emit("  ", group(lightScope, shadowNames)),
]
  .filter((lines) => lines !== "")
  .join("\n");

// ── Inject into DESIGN.md ────────────────────────────────────────────────
const designPath = join(root, "DESIGN.md");
let md = readFileSync(designPath, "utf8");
const eol = md.includes("\r\n") ? "\r\n" : "\n";
const frontMatter = `---${eol}${yaml}${eol}---${eol}${eol}`;

const fmRe = /^---\r?\n[\s\S]*?\r?\n---\r?\n(?:\r?\n)?/;
const existed = fmRe.test(md);
md = existed ? md.replace(fmRe, frontMatter) : frontMatter + md;

writeFileSync(designPath, md, "utf8");
const lightCount = Object.keys(group(lightScope, colorNames)).length;
const darkCount = Object.keys(group(darkScope, colorNames)).length;
console.log(
  `DESIGN.md front-matter ${existed ? "regenerated" : "created"}: ${lightCount} light / ${darkCount} dark color tokens, plus type/space/radius/motion/meter/shadow scales.`,
);
