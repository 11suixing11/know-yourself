/* Generates src/theme/site-tokens.json — the bridge between the CSS custom
 * properties (tokens.css + src/app/refactor.css) and the MUI theme.
 *
 * MUI palette slots need concrete colors, while the site palette lives in
 * oklch() custom properties. This script replicates the CSS cascade
 * (tokens.css :root -> tokens.css .dark -> refactor.css :root -> refactor.css
 * .dark; equal-specificity selectors, later file wins), resolves var() chains,
 * and converts every oklch() to a clipped-sRGB hex. Clipped hex matches what
 * production already ships: Turbopack compiles oklch() to hex double-write,
 * so the browser-visible color in production IS this hex.
 *
 * color-mix(... N%, transparent) tokens cannot become one hex — they are
 * translucent overlays. They are emitted as { ref, pct } pairs and the MUI
 * theme re-applies them as rgba() so translucency is preserved.
 *
 * Run after changing the palette: npm run theme:tokens
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function block(css, selector) {
  const esc = selector.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const m = new RegExp(`(^|[}\\n])\\s*${esc}\\s*\\{`).exec(css);
  if (!m) return "";
  const start = m.index + m[0].length;
  let depth = 1;
  let i = start;
  while (depth > 0 && i < css.length) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}") depth--;
    i++;
  }
  return css.slice(start, i - 1);
}

function decls(blockCss) {
  const out = {};
  const re = /--([a-zA-Z0-9-]+)\s*:\s*([^;]+);/g;
  let m;
  while ((m = re.exec(blockCss))) out[m[1]] = m[2].trim();
  return out;
}

/* oklch -> sRGB hex. Out-of-gamut chroma is channel-clipped, which is what
 * the compiled production CSS effectively delivers as well. */
function oklchToHex(lPct, c, hDeg) {
  const l = lPct / 100;
  const h = (hDeg * Math.PI) / 180;
  const a = c * Math.cos(h);
  const b = c * Math.sin(h);
  const l_ = l + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = l - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = l - 0.0894841775 * a - 1.291485548 * b;
  const L = l_ ** 3;
  const M = m_ ** 3;
  const S = s_ ** 3;
  const lin = [
    4.0767416621 * L - 3.3077115913 * M + 0.2309699292 * S,
    -1.2684380046 * L + 2.6097574011 * M - 0.3413193965 * S,
    -0.0041960863 * L - 0.7034186147 * M + 1.707614701 * S,
  ];
  const channel = (v) => {
    const x = Math.min(1, Math.max(0, v));
    const g = x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055;
    return Math.round(g * 255).toString(16).padStart(2, "0");
  };
  return `#${lin.map(channel).join("")}`;
}

function resolve(merged) {
  const colors = {};
  const mixes = {};
  const visit = (name, seen = new Set()) => {
    if (name in colors) return colors[name];
    if (seen.has(name)) return null;
    seen.add(name);
    const raw = merged[name];
    if (raw == null) return null;
    const v = raw.trim();
    let m;
    if ((m = /^oklch\(\s*([\d.]+)%\s+([\d.]+)\s+([\d.]+)\s*\)$/.exec(v))) {
      colors[name] = oklchToHex(+m[1], +m[2], +m[3]);
    } else if ((m = /^var\(\s*--([\w-]+)\s*\)$/.exec(v))) {
      const got = visit(m[1], seen);
      if (got) colors[name] = got;
    } else if ((m = /^color-mix\(\s*in\s+[\w-]+,\s*var\(\s*--([\w-]+)\s*\)\s+([\d.]+)%,\s*transparent\s*\)$/.exec(v))) {
      mixes[name] = { ref: m[1], pct: +m[2] };
    } else if ((m = /^color-mix\(\s*in\s+[\w-]+,\s*var\(\s*--([\w-]+)\s*\)\s+([\d.]+)%,\s*var\(\s*--([\w-]+)\s*\)\s*\)$/.exec(v))) {
      /* A wash over the page color is equivalent to rgba(ref, pct/100) as long
       * as the component sits on paper — good enough for the bridge theme. */
      mixes[name] = { ref: m[1], pct: +m[2], over: m[3] };
    }
    return colors[name] ?? null;
  };
  for (const name of Object.keys(merged)) visit(name);
  return { colors, mixes };
}

const tokensCss = readFileSync(join(root, "tokens.css"), "utf8");
const refactorCss = readFileSync(join(root, "src/app/refactor.css"), "utf8");

const tokensRoot = decls(block(tokensCss, ":root"));
const tokensDark = decls(block(tokensCss, ".dark"));
const refactorRoot = decls(block(refactorCss, ":root"));
const refactorDark = decls(block(refactorCss, ".dark"));

/* Spread order == CSS source order for the equal-specificity cascade. */
const light = resolve({ ...tokensRoot, ...refactorRoot });
const dark = resolve({ ...tokensRoot, ...tokensDark, ...refactorRoot, ...refactorDark });

const out = {
  generated: new Date().toISOString(),
  note: "Generated by scripts/gen-mui-tokens.mjs — do not edit by hand. oklch source: tokens.css (legacy base) overridden by src/app/refactor.css :root/.dark (morning-light skin).",
  light: light.colors,
  dark: dark.colors,
  mix: light.mixes,
};

const target = join(root, "src/theme/site-tokens.json");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${target}`);
console.log(`light ${Object.keys(out.light).length} colors / dark ${Object.keys(out.dark).length} / mixes ${Object.keys(out.mix).length}`);
